class Checks:
    def __init__(self): self.rows=[]
    def add(self,name,ok,detail=None):
        self.rows.append({'check':name,'passed':bool(ok),'detail':detail})
        return bool(ok)
    def same(self,d,name,*nodes):
        nets=[d.pins.get(tuple(n)) for n in nodes]
        return self.add(name,all(nets) and len(set(nets))==1,{'nodes':nodes,'nets':nets})
    def apart(self,d,name,*nodes):
        nets=[d.pins.get(tuple(n)) for n in nodes]
        return self.add(name,all(nets) and len(set(nets))==len(nets),{'nodes':nodes,'nets':nets})
    def value(self,d,ref,want):
        actual=d.values.get(ref)
        return self.add(ref+' value',value(actual)==value(want),{'expected':want,'actual':actual})

def value(s):
    if s is None:return None
    s=s.strip().lower().replace('ω','').replace('ohm','').replace('f','').replace('h','')
    m=re.fullmatch(r'(\d+(?:\.\d+)?)([rkmungp]?)',s)
    if not m:return s
    return float(m[1])*{'':1,'r':1,'k':1e3,'m':1e6,'u':1e-6,'n':1e-9,'p':1e-12,'g':1e9}[m[2]]

class Circuit:
    def __init__(self): self.pins={};self.groups=defaultdict(set);self.values={};self.footprints={};self.paths={};self.mpns={}
    def add(self,ref,no,net):
        node=(str(ref),str(no))
        if net:self.pins[node]=str(net);self.groups[str(net)].add(node)
    def net(self,ref,no):return self.pins.get((ref,str(no)))
    def nodes(self,ref,no):return self.groups.get(self.net(ref,no),set())

def schematic_netlist(path):
    r=ET.parse(path).getroot();d=Circuit()
    for c in r.findall('components/comp'):
        ref=c.attrib['ref'];d.values[ref]=c.findtext('value');d.footprints[ref]=c.findtext('footprint')
        d.mpns[ref]=next((f.text or '' for f in c.findall('fields/field') if f.attrib.get('name')=='MPN'),'')
    for n in r.findall('nets/net'):
        for pin in n.findall('node'):
            if not pin.attrib['ref'].startswith('#'):d.add(pin.attrib['ref'],pin.attrib['pin'],n.attrib['name'])
    return d

def pcb_circuit(path):
    r=parse(Path(path).read_text());d=Circuit();fps={}
    for f in alln(r,'footprint'):
        p=prop(f,'Reference')
        if not p:continue
        ref=str(p[2]);fps[ref]=f;d.values[ref]=str(prop(f,'Value')[2]);d.footprints[ref]=str(f[1]);d.paths[ref]=get(f,'path',['path',''])[1]
        d.mpns[ref]=str((prop(f,'MPN') or ['property','MPN',''])[2])
        for pad in alln(f,'pad'):
            if pad[1]:
                net=get(pad,'net');d.add(ref,pad[1],net[-1] if net else '__NC_%s_%s'%(ref,pad[1]))
    return d,r,fps

def parity(c,sc,pcb,schpath):
    c.add('Schematic and PCB component references',set(sc.values)==set(pcb.values),{'schematic_only':sorted(set(sc.values)-set(pcb.values)),'pcb_only':sorted(set(pcb.values)-set(sc.values))})
    diffs=[]
    for node in set(sc.pins)|set(pcb.pins):
        # A one-pad unused net may legitimately have a source name or KiCad's
        # autogenerated unconnected name. A missing pad never counts as equal.
        if node not in pcb.pins or node not in sc.pins:diffs.append({'node':node,'reason':'missing pad/node'});continue
        sn=sc.nodes(*node);pn=pcb.nodes(*node)
        if sn!=pn:diffs.append({'node':node,'schematic':sorted(sn),'pcb':sorted(pn)})
    c.add('Schematic/PCB electrical node partitions',not diffs,diffs)
    nd=[]
    for node,snet in sc.pins.items():
        pnet=pcb.pins.get(node)
        if not snet.startswith('unconnected-') and snet!=pnet:nd.append({'node':node,'schematic':snet,'pcb':pnet})
    c.add('Schematic/PCB functional net names exactly match',not nd,nd)
    vd=[];fd=[]
    for ref in set(sc.values)&set(pcb.values):
        if value(sc.values[ref])!=value(pcb.values[ref]):vd.append({'ref':ref,'schematic':sc.values[ref],'pcb':pcb.values[ref]})
        if sc.footprints[ref]!=pcb.footprints[ref]:fd.append({'ref':ref,'schematic':sc.footprints[ref],'pcb':pcb.footprints[ref]})
    c.add('Schematic/PCB values',not vd,vd);c.add('Schematic/PCB footprint links',not fd,fd)
    md=[{'ref':ref,'schematic':sc.mpns.get(ref),'pcb':pcb.mpns.get(ref)} for ref in set(sc.values)&set(pcb.values)
        if not sc.mpns.get(ref) or sc.mpns.get(ref)!=pcb.mpns.get(ref)]
    c.add('Schematic/PCB exact MPN fields',not md,md)
    sch=parse(Path(schpath).read_text());rootid=get(sch,'uuid')[1];pd=[]
    for s in alln(sch,'symbol'):
        ref=str(prop(s,'Reference')[2])
        if ref.startswith('#'):continue
        expected='/'+str(rootid)+'/'+str(get(s,'uuid')[1]);actual=pcb.paths.get(ref)
        if actual!=expected:pd.append({'ref':ref,'expected':expected,'actual':actual})
    c.add('PCB paths match schematic root/symbol UUIDs',not pd,pd)

