# Conservative axis-aligned bounds after rotation; useful for rejecting paste
# apertures/via barrels inside the die-pad window. Native DRC is still required.
def to_global(fp,x,y):
    at=get(fp,'at');a=math.radians(float(at[3]) if len(at)>3 else 0)
    # Native PCB pad coordinates already contain a footprint's B-side flip.
    # Apply only its rotation/translation; a second mirror moves real terminals.
    return (float(at[1])+x*math.cos(a)+y*math.sin(a),float(at[2])-x*math.sin(a)+y*math.cos(a))
def in_poly(p,poly):
    x,y=p;inside=False
    for i,(x1,y1) in enumerate(poly):
        x2,y2=poly[(i+1)%len(poly)]
        if min(x1,x2)-1e-7<=x<=max(x1,x2)+1e-7 and min(y1,y2)-1e-7<=y<=max(y1,y2)+1e-7 and abs((x-x1)*(y2-y1)-(y-y1)*(x2-x1))<1e-7:return True
        if (y1>y)!=(y2>y) and x<(x2-x1)*(y-y1)/(y2-y1)+x1:inside=not inside
    return inside

def mpu_geometry(c,board,fps):
    fp=fps.get('U3')
    if not c.add('MPU footprint present',fp is not None):return
    pads=alln(fp,'pad');nums={str(p[1]) for p in pads}
    c.add('MPU only pins 1–24; no unnamed/25 center pad',nums=={str(i) for i in range(1,25)},sorted(nums))
    # Actual original forbidden EP is 2.7 x 2.8 mm, centered in the package.
    corners=[to_global(fp,x,y) for x,y in [(-1.35,-1.4),(-1.35,1.4),(1.35,1.4),(1.35,-1.4)]]
    # Check center point + inner window for pads with paste; perimeter QFN
    # pads are outside this window. Pad margin uses actual pad dimensions.
    paste=[]
    for p in pads:
        layers=get(p,'layers',[])[1:]
        if not any(x in ['F.Paste','B.Paste','*.Paste'] for x in layers):continue
        at=get(p,'at');sz=get(p,'size');x,y=float(at[1]),float(at[2]);w,h=float(sz[1]),float(sz[2])
        a=math.radians((float(at[3]) if len(at)>3 else 0)-(float(get(fp,'at')[3]) if len(get(fp,'at'))>3 else 0))
        dx=(abs(w*math.cos(a))+abs(h*math.sin(a)))/2;dy=(abs(w*math.sin(a))+abs(h*math.cos(a)))/2
        if abs(x)<1.35+dx-1e-5 and abs(y)<1.4+dy-1e-5:paste.append(str(p[1]))
    c.add('No MPU paste aperture overlaps forbidden die window',not paste,paste)
    keep=[]
    for z in alln(board,'zone'):
        ko=get(z,'keepout');poly=get(z,'polygon');layers=get(z,'layers',get(z,'layer',[]))[1:]
        if not ko or not poly or get(fp,'layer')[1] not in layers:continue
        points=[(float(p[1]),float(p[2])) for p in alln(get(poly,'pts'),'xy')]
        if all(in_poly(p,points) for p in corners) and all(get(ko,k,[k,None])[1]=='not_allowed' for k in ['tracks','vias','pads','copperpour']):keep.append(str(get(z,'uuid')[1]))
    c.add('MPU die window covered by copper/track/via/pad keepout',bool(keep),keep)
    vias=[]
    for v in alln(board,'via'):
        at=get(v,'at');p=(float(at[1]),float(at[2]));radius=float(get(v,'size')[1])/2
        # Inflate via centers conservatively by barrel diameter bounds.
        cx,cy=to_global(fp,0,0)
        minx=min(p[0] for p in corners);maxx=max(p[0] for p in corners);miny=min(p[1] for p in corners);maxy=max(p[1] for p in corners)
        if minx-radius<p[0]<maxx+radius and miny-radius<p[1]<maxy+radius:vias.append(p)
    c.add('No through-via barrels in MPU die window',not vias,vias)

def pico_geometry(c,board,fps):
    """PICO thermal geometry is different from the MPU's forbidden die pad."""
    fp=fps.get('U4')
    if not c.add('PICO footprint present',fp is not None):return
    ep=next((p for p in alln(fp,'pad') if p[1]=='0'),None)
    if not c.add('PICO logical pad0 / physical49 thermal ground present',ep is not None):return
    size=get(ep,'size');layers=get(ep,'layers',[])[1:];net=get(ep,'net',[])
    c.add('PICO thermal copper 4.5mm square grounded',
          all(abs(float(x)-4.5)<.005 for x in size[1:3]) and net and net[-1]=='GND',
          {'size':size[1:3],'net':net})
    margin=get(ep,'solder_mask_margin',['solder_mask_margin','0'])
    c.add('PICO solder-mask-defined 4.0mm opening',
          'F.Mask' in layers and all(abs(float(x)+2*float(margin[1])-4.0)<.005 for x in size[1:3]),
          {'layers':layers,'local_mask_margin':margin[1]})
    c.add('PICO EP has no full-area paste aperture','F.Paste' not in layers and '*.Paste' not in layers,layers)
    windows=[]
    for p in alln(fp,'pad'):
        ls=get(p,'layers',[])[1:]
        if 'F.Paste' in ls and not any(x in ['F.Cu','B.Cu','*.Cu'] for x in ls):
            at=get(p,'at');sz=get(p,'size');windows.append((float(at[1]),float(at[2]),float(sz[1]),float(sz[2])))
    for shape in alln(fp,'fp_rect'):
        if get(shape,'layer',['layer',''])[1]!='F.Paste':continue
        start=get(shape,'start');end=get(shape,'end')
        if start and end:
            x1,y1=map(float,start[1:3]);x2,y2=map(float,end[1:3])
            windows.append(((x1+x2)/2,(y1+y2)/2,abs(x2-x1),abs(y2-y1)))
    expected=[(x,y) for x in [-1.575,-.525,.525,1.575] for y in [-1.575,-.525,.525,1.575]]
    c.add('PICO sixteen 0.75mm stencil windows / 0.30mm gaps',len(windows)==16 and all(
        any(abs(x-ex)<.005 and abs(y-ey)<.005 and abs(w-.75)<.005 and abs(h-.75)<.005
            for x,y,w,h in windows) for ex,ey in expected),windows)
    cx,cy=to_global(fp,0,0);a=math.radians(float(get(fp,'at')[3]) if len(get(fp,'at'))>3 else 0)
    thermal=[]
    for v in alln(board,'via'):
        at=get(v,'at');dx=float(at[1])-cx;dy=float(at[2])-cy
        x=dx*math.cos(a)-dy*math.sin(a);y=dx*math.sin(a)+dy*math.cos(a)
        if abs(x)<=2.26 and abs(y)<=2.26:
            thermal.append((x,y,float(get(v,'drill')[1]),float(get(v,'size')[1]),get(v,'net',['net',''])[-1]))
    grid=[(x,y) for x in [-2,-1.05,0,1.05,2] for y in [-2,-1.05,0,1.05,2]
          if not(abs(x)==2 and abs(y)==2)]
    c.add('PICO twenty-one 0.25mm ground thermal vias / >=0.10mm annulus',len(thermal)==21 and all(
        any(abs(x-ex)<.005 and abs(y-ey)<.005 and abs(d-.25)<.002 and (s-d)/2>=.0999 and n=='GND'
            for x,y,d,s,n in thermal) for ex,ey in grid),thermal)

def stack_geometry(c,board):
    """Check the actual inner-layer use, not just a plane's display name."""
    layers={str(n[1]) for n in get(board,'layers',[])[1:] if isinstance(n,list)}
    if 'In1.Cu' not in layers:return  # Original two-layer engineering source.
    copper=[str(n[1]) for n in get(board,'layers',[])[1:] if isinstance(n,list) and str(n[1]).endswith('.Cu')]
    c.add('Multilayer revision has reviewed copper layer order',copper in [
        ['F.Cu','In1.Cu','In2.Cu','B.Cu'],
        ['F.Cu','In1.Cu','In2.Cu','In3.Cu','In4.Cu','B.Cu']],copper)
    dedicated=[('In1.Cu','L2')]+([('In4.Cu','L5')] if 'In4.Cu' in layers else [])
    for layer,label in dedicated:
        foreign=[]
        for name in ['segment','arc']:
            for t in alln(board,name):
                if get(t,'layer',['layer',''])[1]==layer and get(t,'net',['net',''])[-1]!='GND':
                    foreign.append({'kind':name,'uuid':get(t,'uuid',['uuid',''])[1],'net':get(t,'net')})
        plane=[];bad=[]
        for z in alln(board,'zone'):
            if get(z,'keepout'):continue
            ls=get(z,'layers',get(z,'layer',[]))[1:]
            if layer not in ls:continue
            if get(z,'net',['net',''])[-1]=='GND':plane.append(z)
            else:bad.append(get(z,'net'))
        c.add('Dedicated '+label+' ground plane has no foreign tracks or pours',bool(plane) and not foreign and not bad,
              {'ground_planes':len(plane),'foreign_tracks':foreign,'foreign_pours':bad})
    stack=get(get(board,'setup',[]),'stackup',[])
    thicknesses=[float(get(n,'thickness')[1]) for n in alln(stack,'layer') if get(n,'thickness')]
    total=sum(thicknesses);model=float(get(get(board,'general'),'thickness')[1])
    c.add('Nominal stack thickness agrees with all copper/dielectric/mask layers',
          bool(thicknesses) and abs(total-model)<.00001,{'stack_sum_mm':total,'model_mm':model,'scope':'Nominal CAD bookkeeping; delivered stack/tolerance requires fabricator confirmation'})


def run_cli(cli,args):
    result=subprocess.run([str(cli),*map(str,args)],text=True,capture_output=True,env={**os.environ,'PYTHONDONTWRITEBYTECODE':'1'})
    return {'returncode':result.returncode,'stdout':result.stdout.strip(),'stderr':result.stderr.strip()}

def manufacturing_rules(c,project,stem):
    rules=project.get('board',{}).get('design_settings',{}).get('rules',{})
    try:
        web=float(rules.get('solder_mask_min_width'))
        clearance=float(rules.get('solder_mask_to_copper_clearance'))
        ok=web>=.10 and clearance>=.09
    except (TypeError,ValueError):
        ok=False
    c.add(stem+' manufacturing solder-mask rules',ok,
          {k:rules.get(k) for k in ['solder_mask_min_width','solder_mask_to_copper_clearance']})

def validate_board(cli,folder,stem,c,temp,drc=False):
    sch=folder/(stem+'.kicad_sch');pcb=folder/(stem+'.kicad_pcb');xml=temp/(stem+'.xml');erc=temp/(stem+'_erc.json')
    manufacturing_rules(c,json.loads((folder/(stem+'.kicad_pro')).read_text()),stem)
    export=run_cli(cli,['sch','export','netlist','--format','kicadxml','--output',xml,sch]);c.add(stem+' native netlist export',export['returncode']==0,export)
    if export['returncode']!=0:return None,None,None
    report=run_cli(cli,['sch','erc','--format','json','--severity-all','--exit-code-violations','--output',erc,sch]);ercdata=json.loads(erc.read_text()) if erc.exists() else {}
    violations=[v for s in ercdata.get('sheets',[]) for v in s.get('violations',[])]
    c.add(stem+' native ERC all severities',report['returncode']==0 and not violations,{'command':report,'violations':violations,'ignored_checks':ercdata.get('ignored_checks')})
    sc=schematic_netlist(xml);pd,tree,fps=pcb_circuit(pcb);parity(c,sc,pd,sch)
    if drc:
        out=temp/(stem+'_drc.json');r=run_cli(cli,['pcb','drc','--format','json','--all-track-errors','--schematic-parity','--refill-zones','--severity-all','--exit-code-violations','--output',out,pcb])
        data=json.loads(out.read_text()) if out.exists() else {}
        parity_ran='Failed to fetch schematic netlist' not in r['stdout']+r['stderr']
        c.add(stem+' native DRC all errors/parity',r['returncode']==0 and parity_ran and all(
            data.get(key)==[] for key in ['violations','unconnected_items','schematic_parity']),
            {'command':r,'report':data})
    return sc,tree,fps

